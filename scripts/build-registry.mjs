#!/usr/bin/env node
/**
 * Builds everything derived from the source registry:
 *
 *   1. `shadcn registry validate`  — schema, unique names, include rules, file paths
 *   2. `shadcn build`              — public/r/<name>.json + flattened public/r/registry.json
 *   3. __registry__/index.tsx      — lazy import map of `registry:example` items for docs previews
 *   4. public/llms.txt             — agent-readable catalog
 *
 * Runs before `vite dev` and `vite build` (see package.json scripts).
 */
import { execFileSync } from "node:child_process"
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const shadcn = path.join(root, "node_modules", ".bin", process.platform === "win32" ? "shadcn.cmd" : "shadcn")
const outDir = path.join(root, "public", "r")
const baseUrl = (process.env.VITE_BASE_URL ?? "https://ui.tanfust.com").replace(/\/$/, "")

function run(args) {
  execFileSync(shadcn, args, { cwd: root, stdio: "inherit" })
}

step("validate", () => run(["registry", "validate"]))
step("build", () => run(["build", "--output", outDir]))

const catalog = JSON.parse(readFileSync(path.join(outDir, "registry.json"), "utf8"))
const items = catalog.items ?? []
const publicItems = items.filter((i) => i.type !== "registry:example" && i.type !== "registry:internal")
const examples = items.filter((i) => i.type === "registry:example")

step("src/__registry__/index.tsx", () => {
  const dir = path.join(root, "src", "__registry__")
  if (!existsSync(dir)) mkdirSync(dir)
  const entries = examples
    .map((item) => {
      const file = item.files?.[0]?.path
      if (!file) return null
      const modulePath = "@/" + file.replace(/^src\//, "").replace(/\.(tsx|ts|jsx|js)$/, "")
      return `  "${item.name}": {
    name: "${item.name}",
    file: "${file}",
    component: React.lazy(() => import("${modulePath}")),
  },`
    })
    .filter(Boolean)
    .join("\n")

  writeFileSync(
    path.join(dir, "index.tsx"),
    `// @ts-nocheck
// GENERATED by scripts/build-registry.mjs — do not edit.
import * as React from "react"

export type IndexEntry = {
  name: string
  file: string
  component: React.LazyExoticComponent<React.ComponentType<Record<string, unknown>>>
}

export const Index: Record<string, IndexEntry> = {
${entries}
}
`
  )
})

step("public/llms.txt", () => {
  const lines = [
    `# ${catalog.name === "tanfust" ? "Tanfust UI" : catalog.name}`,
    "",
    "> Essential components, hooks and flows for everyday sites and apps, distributed as a shadcn-compatible registry. Items are installed as source into the consumer's project.",
    "",
    "## Install",
    "",
    "```bash",
    `npx shadcn@latest registry add @tanfust=${baseUrl}/r/{name}.json`,
    "npx shadcn@latest add @tanfust/<item>",
    `npx shadcn@latest init ${baseUrl}/r/tanfust.json   # new project with the Tanfust design system`,
    "npx shadcn@latest mcp init --client claude          # expose the registry to an MCP client",
    "```",
    "",
    `Catalog (machine-readable): ${baseUrl}/r/registry.json`,
    `Item payloads: ${baseUrl}/r/<item>.json`,
    "",
    `## Items (${publicItems.length})`,
    "",
  ]
  if (publicItems.length === 0) {
    lines.push("_No items published yet._")
  }
  for (const item of publicItems) {
    const desc = item.description ? ` — ${item.description}` : ""
    lines.push(`- [${item.name}](${baseUrl}/r/${item.name}.json) (${item.type})${desc}`)
    lines.push(`  \`npx shadcn@latest add @tanfust/${item.name}\``)
  }
  lines.push("")
  writeFileSync(path.join(root, "public", "llms.txt"), lines.join("\n"))
})

console.log(`\n✔ registry built: ${publicItems.length} item(s), ${examples.length} example(s) → public/r`)

function step(name, fn) {
  console.log(`\n▸ ${name}`)
  fn()
}
